"""Stage-6 oracle: the AITR comparator aligns a runtime trace to the static
disassembly with no unexplained pc.

Without the engine, a synthetic trace is generated by walking each script's
static instructions (ai_runtime.simulate_trace) and fed back to the comparator.
The guarantee under test - every runtime pc is a static instruction start whose
opcode matches - must hold 100%: aligned == total, 0 mismatches, 0 unknown pc,
for every script. When real OpenBW engine logs replace the synthetic trace they
parse into the same AitrEvent stream and use the same compare(), so a genuine
static-vs-runtime divergence would surface as a mismatch here.

    py test_ai_runtime.py
"""
import sys
import os

sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..'))
sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', '..', 'tools', 'ai'))
from common import BW, need, report      # noqa: E402
import mpq                               # noqa: E402
import ai_bin                            # noqa: E402
import ai_runtime                        # noqa: E402


def main():
    need(BW, 'Brood War install')
    files = ai_bin.load_from_chain(mpq.MpqChain(BW))
    if not files:
        print('SKIP: no AI script files')
        sys.exit(77)
    ok = total = 0
    events = 0
    bad = []
    for source, f in sorted(files.items()):
        for e in f.entries:
            if not e.used:
                continue
            total += 1
            trace = ai_runtime.simulate_trace(f, e)
            diff = ai_runtime.compare(f, e, trace)
            events += diff.total
            if diff.ok and diff.aligned == diff.total and diff.total > 0:
                ok += 1
            else:
                bad.append((e.fourcc, len(diff.mismatches), len(diff.unknown_pc)))
    rc = report('ai: runtime trace aligns to static', ok, total,
                '(%d trace events aligned; bad=%s)'
                % (events, bad[:3] if bad else 'none'))
    sys.exit(rc)


if __name__ == '__main__':
    main()
