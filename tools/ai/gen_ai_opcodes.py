#!/usr/bin/env python3
"""Generate tools/ai/ai_opcodes.py from a copy of PyMS's AIBIN.py.

Same pattern as tools/gen_vp8_tables.py: the opcode NAMES and per-opcode
ARGUMENT TYPE lists are borrowed format data (there is no normative spec for the
StarCraft AI VM), so they are cut mechanically out of the reference rather than
retyped by hand - a transcription typo would be impossible to spot otherwise.

Provenance: the opcode label / short-label / parameter tables come from PyMS
(poiuyqwert/PyMS, MIT) `PyMS/FileFormats/AIBIN.py`. Fetch (not committed, the
scratch copy vanishes between sessions):

    curl.exe -sSL --ssl-no-revoke \
      https://raw.githubusercontent.com/poiuyqwert/PyMS/master/PyMS/FileFormats/AIBIN.py \
      -o scratch_ai/AIBIN.py

The argument BYTE SIZES below are read from PyMS's ai_* reader functions (each
returns [size, value] and the decompiler advances curoffset += size), and are
re-checked here against the real Brood War files by the linear-disassembly
oracle in tests/ai/test_ai_disasm.py (the whole code region must decode to a
whole number of instructions ending exactly on the entry table).
"""
import ast
import os
import re
import sys

# ai_* reader function -> (type name, on-disk byte size). size -1 == variable
# (null-terminated string). Read from PyMS AIBIN.py ai_* return values.
TYPE_SIZE = {
    'ai_byte': ('byte', 1),
    'ai_word': ('word', 2),
    'ai_dword': ('dword', 4),
    'ai_address': ('address', 2),      # jump target (offset within the file)
    'ai_unit': ('unit', 2),
    'ai_building': ('building', 2),
    'ai_military': ('military', 2),
    'ai_ggmilitary': ('gg_military', 2),
    'ai_agmilitary': ('ag_military', 2),
    'ai_gamilitary': ('ga_military', 2),
    'ai_aamilitary': ('aa_military', 2),
    'ai_upgrade': ('upgrade', 2),
    'ai_technology': ('technology', 2),
    'ai_string': ('string', -1),
    'ai_compare': ('compare', 1),
}


def _extract_list(src, name):
    """Return the source text of `self.NAME = [ ... ]` (or `NAME = [ ... ]`)."""
    m = re.search(r'\b' + re.escape(name) + r'\s*=\s*\[', src)
    if not m:
        raise SystemExit('list %r not found' % name)
    i = m.end() - 1
    depth = 0
    for j in range(i, len(src)):
        if src[j] == '[':
            depth += 1
        elif src[j] == ']':
            depth -= 1
            if depth == 0:
                return src[i:j + 1]
    raise SystemExit('unterminated list %r' % name)


def _string_list(src, name):
    return [str(x) for x in ast.literal_eval(_extract_list(src, name))]


def _parameters(src):
    """Parse the `self.parameters = [ ... ]` list into a list of (short_name,
    [type_name...]). Entries are `None` or `[self.ai_x, ...]  # short_name`."""
    block = _extract_list(src, 'self.parameters')
    out = []
    for line in block.splitlines():
        line = line.strip().rstrip(',')
        if line in ('[', ']') or not line:
            continue
        cm = re.search(r'#\s*(\S+)', line)
        short = cm.group(1) if cm else None
        code = line.split('#', 1)[0].strip().rstrip(',')
        if code.startswith('None'):
            out.append((short, []))
            continue
        funcs = re.findall(r'self\.(ai_\w+)', code)
        if not funcs:
            continue
        args = []
        for f in funcs:
            if f not in TYPE_SIZE:
                raise SystemExit('unknown arg reader %r' % f)
            args.append(TYPE_SIZE[f])
        out.append((short, args))
    return out


HEADER = '''\
#!/usr/bin/env python3
"""StarCraft AI-script opcode registry - GENERATED by tools/ai/gen_ai_opcodes.py.
Do not hand-edit; regenerate from PyMS AIBIN.py (see the generator for the fetch
command and the provenance note).

OPCODES[i] = OpcodeSpec for opcode byte i. Each spec carries the canonical short
name, the verbose label, and the ordered argument list as (type_name, size)
pairs (size -1 == variable-length null-terminated string). ARG type 'address' is
a 2-byte jump target (an offset within the .bin file).

There are %d opcodes (0..%d). Opcode is one byte; a byte >= %d is invalid.
"""
from dataclasses import dataclass, field


@dataclass(frozen=True)
class OpcodeSpec:
    opcode: int
    name: str            # canonical short name, e.g. "goto"
    label: str           # verbose label, e.g. "Goto"
    args: tuple          # tuple of (type_name, size_bytes); size -1 = variable
    control_flow: str    # '', 'jump', 'cond_jump', 'multi_jump', 'call',
                         # 'terminate', 'spawn'

    @property
    def has_variable_arg(self):
        return any(sz < 0 for _, sz in self.args)

    def fixed_size(self):
        """Total on-disk size incl. the 1-byte opcode, or None if variable."""
        if self.has_variable_arg:
            return None
        return 1 + sum(sz for _, sz in self.args)

    @property
    def address_arg_indices(self):
        return tuple(i for i, (t, _) in enumerate(self.args) if t == 'address')

'''


# control-flow class per opcode short name. This annotation is OURS (derived
# from the opcode semantics), not copied - it drives the CFG stage. Any opcode
# with an 'address' arg not listed here defaults to 'cond_jump'.
CONTROL_FLOW = {
    'goto': 'jump',
    'stop': 'terminate',
    'return': 'terminate',
    'kill_thread': 'terminate',
    'fatal_error': 'terminate',
    'restart': 'terminate',
    'call': 'call',
    'race_jump': 'multi_jump',
    'multirun': 'spawn',
}


def build(src):
    labels = _string_list(src, 'labels')
    short = _string_list(src, 'short_labels')
    params = _parameters(src)
    n = len(params)
    if not (len(labels) == len(short) == n):
        raise SystemExit('length mismatch labels=%d short=%d params=%d'
                         % (len(labels), len(short), n))
    lines = [HEADER % (n, n - 1, n)]
    lines.append('OPCODES = [')
    for i in range(n):
        pshort, args = params[i]
        name = short[i] if short[i] else (pshort or ('op%d' % i))
        args_repr = tuple((t, s) for t, s in args)
        cf = CONTROL_FLOW.get(name, '')
        if not cf and any(t == 'address' for t, _ in args):
            cf = 'cond_jump'
        lines.append('    OpcodeSpec(%d, %r, %r, %r, %r),'
                     % (i, name, labels[i], args_repr, cf))
    lines.append(']')
    lines.append('')
    lines.append('OPCODE_BY_NAME = {o.name: o for o in OPCODES}')
    lines.append('MAX_OPCODE = %d' % (n - 1))
    lines.append('')
    return '\n'.join(lines)


if __name__ == '__main__':
    here = os.path.dirname(__file__)
    src_path = sys.argv[1] if len(sys.argv) > 1 \
        else os.path.join(here, '..', '..', 'scratch_ai', 'AIBIN.py')
    out_path = sys.argv[2] if len(sys.argv) > 2 \
        else os.path.join(here, 'ai_opcodes.py')
    with open(src_path, 'r', encoding='utf-8', errors='replace') as f:
        src = f.read()
    out = build(src)
    with open(out_path, 'w', encoding='utf-8') as f:
        f.write(out)
    # quick self-report
    ns = {}
    exec(compile(out, out_path, 'exec'), ns)
    ops = ns['OPCODES']
    print('wrote %s: %d opcodes' % (out_path, len(ops)))
    print('  variable-size opcodes:', [o.name for o in ops if o.has_variable_arg])
    print('  control-flow:', sorted(set(o.control_flow for o in ops if o.control_flow)))
