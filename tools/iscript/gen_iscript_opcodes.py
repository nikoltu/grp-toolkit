#!/usr/bin/env python3
"""Generate tools/iscript/iscript_opcodes.py from a copy of PyMS's IScriptBIN.py.

Same pattern as tools/ai/gen_ai_opcodes.py and tools/gen_vp8_tables.py: the
opcode NAMES and per-opcode ARGUMENT TYPE lists are borrowed format data (there
is no normative spec for the StarCraft iscript animation VM), so they are cut
mechanically out of the reference rather than retyped by hand.

Provenance: the OPCODES table, the type_* argument sizes, the 28 animation names
(HEADER) and the type->animation-count map (ENTRY_TYPES) come from PyMS
(poiuyqwert/PyMS, MIT) `PyMS/FileFormats/IScriptBIN.py`. Fetch (not committed):

    curl.exe -sSL --ssl-no-revoke \
      https://raw.githubusercontent.com/poiuyqwert/PyMS/master/PyMS/FileFormats/IScriptBIN.py \
      -o scratch/IScriptBIN.py

The argument BYTE SIZES are each type_* function's `return N` for stage==None,
and are re-checked against the real Brood War iscript.bin by the linear-decode
oracle in tests/iscript/test_iscript.py (every animation must decode to a whole
number of opcodes ending on a block terminator, every jump landing on an opcode
boundary).

    py gen_iscript_opcodes.py scratch/IScriptBIN.py -o iscript_opcodes.py
"""
import argparse
import ast
import re

# type_* -> (type name, on-disk byte size). size -1 = variable: a 1-byte count
# followed by that many of the opcode's NEXT parameter (playsndrand/attackmelee).
TYPE_SIZE = {
    'type_frame': ('frame', 2), 'type_frameset': ('frameset', 1),
    'type_bframe': ('bframe', 1), 'type_byte': ('byte', 1),
    'type_sbyte': ('sbyte', 1), 'type_label': ('label', 2),
    'type_imageid': ('imageid', 2), 'type_spriteid': ('spriteid', 2),
    'type_flingyid': ('flingyid', 2), 'type_overlayid': ('overlayid', 1),
    'type_flipstate': ('flipstate', 1), 'type_soundid': ('soundid', 2),
    'type_sounds': ('sounds', -1), 'type_signalid': ('signalid', 1),
    'type_weapon': ('weapon', 1), 'type_weaponid': ('weaponid', 1),
    'type_speed': ('speed', 2), 'type_gasoverlay': ('gasoverlay', 1),
    'type_short': ('short', 2),
}

# control-flow class per opcode name (our own classification, not borrowed).
CONTROL_FLOW = {
    'goto': 'jump', 'end': 'terminate', 'return': 'terminate', 'call': 'call',
    'randcondjmp': 'cond_jump', 'pwrupcondjmp': 'cond_jump',
    'trgtrangecondjmp': 'cond_jump', 'trgtarccondjmp': 'cond_jump',
    'curdirectcondjmp': 'cond_jump', 'liftoffcondjmp': 'cond_jump',
}


def _cut_block(src, name):
    """Return the source text of a top-level `name = [ ... ]` list literal."""
    m = re.search(r'^%s = \[' % re.escape(name), src, re.M)
    if not m:
        raise SystemExit('could not find %s' % name)
    i = m.end() - 1
    depth = 0
    for j in range(i, len(src)):
        if src[j] == '[':
            depth += 1
        elif src[j] == ']':
            depth -= 1
            if depth == 0:
                return src[i:j + 1]
    raise SystemExit('unbalanced %s' % name)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('iscriptbin', help='path to PyMS IScriptBIN.py')
    ap.add_argument('-o', default='iscript_opcodes.py')
    args = ap.parse_args()
    src = open(args.iscriptbin, encoding='utf-8').read()

    # OPCODES: replace type_* refs with their string names so it literal-evals
    ob = _cut_block(src, 'OPCODES')
    ob = re.sub(r'\btype_(\w+)\b', r"'type_\1'", ob)
    opcodes = ast.literal_eval(ob)

    hb = _cut_block(src, 'HEADER')
    header = [t[0] for t in ast.literal_eval(hb)]

    eb = re.search(r'ENTRY_TYPES = (\{[^}]*\})', src).group(1)
    entry_types = ast.literal_eval(eb)

    rows = []
    for op, entry in enumerate(opcodes):
        name = entry[0][0]
        argl = []
        for t in entry[1]:
            tn, sz = TYPE_SIZE[t]
            argl.append((tn, sz))
        rows.append((op, name, tuple(argl), CONTROL_FLOW.get(name, '')))

    out = ['#!/usr/bin/env python3',
           '"""StarCraft iscript opcode registry - GENERATED by '
           'gen_iscript_opcodes.py.',
           'Do not hand-edit; regenerate from PyMS IScriptBIN.py (see the '
           'generator for the',
           'fetch command and the provenance note).',
           '',
           'OPCODES[i] = OpcodeSpec for opcode byte i. args is a tuple of '
           '(type, size);',
           "size -1 == a variable 'sounds' arg: a 1-byte count then that many of "
           'the NEXT arg.',
           'HEADER = the 28 animation names; ENTRY_TYPES maps a header type byte '
           'to how many',
           'animation-offset u16s the header stores (spec 6.x, measured against '
           'the real file).',
           '"""',
           'from dataclasses import dataclass',
           '',
           '',
           '@dataclass(frozen=True)',
           'class OpcodeSpec:',
           '    opcode: int',
           '    name: str',
           '    args: tuple            # ((type_name, size_bytes), ...); -1 = '
           'variable sounds',
           "    control_flow: str      # '', 'jump', 'cond_jump', 'call', "
           "'terminate'",
           '',
           '    @property',
           '    def has_variable_arg(self):',
           '        return any(sz < 0 for _, sz in self.args)',
           '',
           '    @property',
           '    def label_arg_indices(self):',
           "        return tuple(i for i, (t, _) in enumerate(self.args) "
           "if t == 'label')",
           '',
           '',
           'OPCODES = [']
    for op, name, oargs, cf in rows:
        out.append('    OpcodeSpec(%d, %r, %r, %r),' % (op, name, oargs, cf))
    out.append(']')
    out.append('')
    out.append('OPCODE_BY_NAME = {o.name: o for o in OPCODES}')
    out.append('MAX_OPCODE = %d' % (len(rows) - 1))
    out.append('')
    out.append('# 28 animation slots (header offset list order)')
    out.append('HEADER = %r' % (tuple(header),))
    out.append('')
    out.append('# header type byte -> number of animation-offset u16s stored')
    out.append('ENTRY_TYPES = %r' % (dict(sorted(entry_types.items())),))
    out.append('')
    open(args.o, 'w', encoding='utf-8').write('\n'.join(out))
    print('wrote %s: %d opcodes, %d animations, %d header types'
          % (args.o, len(rows), len(header), len(entry_types)))


if __name__ == '__main__':
    main()
